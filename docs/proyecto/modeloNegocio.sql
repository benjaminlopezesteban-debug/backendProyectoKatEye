-- ============================================================================
-- KatEye - Modelo de negocio reducido (MVP)
-- SGBD destino : Oracle Database 12c o superior
-- Uso          : Importar en Oracle SQL Developer Data Modeler
--                (Archivo > Importar > Modelo de datos > DDL)
-- Normalizacion: Tercera Forma Normal (3FN)
-- Criterio     : Solo atributos minimos funcionales. Se omiten marcas de
--                creacion/actualizacion (creado_en, actualizado_en, etc.).
--                Se conservan solo fechas con valor de negocio: vigencia de
--                oferta, expiracion, fecha de venta/emision y fecha de un
--                evento en el historial o en el registro de intentos.
-- Nota         : Las FK se declaran fisicamente para que Data Modeler
--                reconstruya las relaciones. En un despliegue real de
--                microservicios estas claves son referencias logicas.
-- ============================================================================

SET DEFINE OFF;

-- ============================================================================
-- 1. CATALOGOS GEOGRAFICOS
-- ============================================================================

CREATE TABLE REGION (
    CODIGO VARCHAR2(10)  NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_REGION PRIMARY KEY (CODIGO)
);

CREATE TABLE COMUNA (
    CODIGO        VARCHAR2(10)  NOT NULL,
    NOMBRE        VARCHAR2(100) NOT NULL,
    REGION_CODIGO VARCHAR2(10)  NOT NULL,
    CONSTRAINT PK_COMUNA PRIMARY KEY (CODIGO),
    CONSTRAINT UQ_COMUNA_NOMBRE UNIQUE (REGION_CODIGO, NOMBRE),
    CONSTRAINT FK_COMUNA_REGION FOREIGN KEY (REGION_CODIGO)
        REFERENCES REGION (CODIGO)
);

-- ============================================================================
-- 2. USUARIOS Y SEGURIDAD
-- ============================================================================

CREATE TABLE ROL (
    ID     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(30) NOT NULL,
    CONSTRAINT PK_ROL PRIMARY KEY (ID),
    CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIO (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE        VARCHAR2(100) NOT NULL,
    CORREO        VARCHAR2(100) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    TELEFONO      VARCHAR2(20),
    REGION_CODIGO VARCHAR2(10)  NOT NULL,
    COMUNA_CODIGO VARCHAR2(10)  NOT NULL,
    ROL_ID        NUMBER(19)    NOT NULL,
    ACTIVO        CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
    CONSTRAINT FK_USUARIO_REGION FOREIGN KEY (REGION_CODIGO)
        REFERENCES REGION (CODIGO),
    CONSTRAINT FK_USUARIO_COMUNA FOREIGN KEY (COMUNA_CODIGO)
        REFERENCES COMUNA (CODIGO),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ROL_ID)
        REFERENCES ROL (ID),
    CONSTRAINT CHK_USUARIO_ACTIVO CHECK (ACTIVO IN ('S','N'))
);

-- RN-10: el correo es unico sin distinguir mayusculas.
CREATE UNIQUE INDEX UQ_USUARIO_CORREO_CI ON USUARIO (UPPER(CORREO));

CREATE TABLE RECUPERACION (
    ID         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID NUMBER(19)   NOT NULL,
    TOKEN_HASH VARCHAR2(255) NOT NULL,
    EXPIRA_EN  TIMESTAMP    NOT NULL,
    CONSTRAINT PK_RECUPERACION PRIMARY KEY (ID),
    CONSTRAINT UQ_RECUPERACION_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_RECUPERACION_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIO (ID) ON DELETE CASCADE
);

CREATE TABLE INTENTO_ACCESO (
    ID         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID NUMBER(19),
    TIPO       VARCHAR2(20) NOT NULL,
    CORREO     VARCHAR2(100),
    IP         VARCHAR2(45),
    EXITOSO    CHAR(1)     DEFAULT 'N' NOT NULL,
    FECHA      TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INTENTO_ACCESO PRIMARY KEY (ID),
    CONSTRAINT FK_INTENTO_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIO (ID),
    CONSTRAINT CHK_INTENTO_TIPO
        CHECK (TIPO IN ('LOGIN','REGISTRO','RECUPERACION','CONTACTO')),
    CONSTRAINT CHK_INTENTO_EXITOSO CHECK (EXITOSO IN ('S','N'))
);

-- ============================================================================
-- 3. CATALOGO
-- ============================================================================

CREATE TABLE CATEGORIA (
    ID     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    SLUG   VARCHAR2(60)  NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    ORDEN  NUMBER(5)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID),
    CONSTRAINT UQ_CATEGORIA_SLUG UNIQUE (SLUG)
);

CREATE TABLE PRODUCTO (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODIGO        VARCHAR2(20)  NOT NULL,
    NOMBRE        VARCHAR2(100) NOT NULL,
    DESCRIPCION   VARCHAR2(500),
    PRECIO        NUMBER(10)    DEFAULT 0 NOT NULL,
    STOCK         NUMBER(10)    DEFAULT 0 NOT NULL,
    STOCK_CRITICO NUMBER(10),
    CATEGORIA_ID  NUMBER(19)    NOT NULL,
    ACTIVO        CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_PRODUCTO PRIMARY KEY (ID),
    CONSTRAINT UQ_PRODUCTO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (CATEGORIA_ID)
        REFERENCES CATEGORIA (ID),
    CONSTRAINT CHK_PRODUCTO_ACTIVO CHECK (ACTIVO IN ('S','N')),
    CONSTRAINT CHK_PRODUCTO_CODIGO CHECK (LENGTH(CODIGO) >= 3),
    CONSTRAINT CHK_PRODUCTO_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CHK_PRODUCTO_STOCK CHECK (STOCK >= 0),
    CONSTRAINT CHK_PRODUCTO_STOCK_CRIT CHECK (STOCK_CRITICO IS NULL OR STOCK_CRITICO >= 0)
);

CREATE TABLE PRODUCTO_IMAGEN (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PRODUCTO_ID NUMBER(19)   NOT NULL,
    URL         VARCHAR2(500) NOT NULL,
    ORDEN       NUMBER(5)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PRODUCTO_IMAGEN PRIMARY KEY (ID),
    CONSTRAINT UQ_PRODUCTO_IMAGEN_ORDEN UNIQUE (PRODUCTO_ID, ORDEN),
    CONSTRAINT FK_PRODUCTO_IMAGEN_PROD FOREIGN KEY (PRODUCTO_ID)
        REFERENCES PRODUCTO (ID) ON DELETE CASCADE
);

CREATE TABLE OFERTA (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PRODUCTO_ID     NUMBER(19) NOT NULL,
    PRECIO_ANTERIOR NUMBER(10) NOT NULL,
    PRECIO_OFERTA   NUMBER(10) NOT NULL,
    DESDE           TIMESTAMP  NOT NULL,
    HASTA           TIMESTAMP  NOT NULL,
    CONSTRAINT PK_OFERTA PRIMARY KEY (ID),
    CONSTRAINT FK_OFERTA_PRODUCTO FOREIGN KEY (PRODUCTO_ID)
        REFERENCES PRODUCTO (ID) ON DELETE CASCADE,
    CONSTRAINT CHK_OFERTA_PRECIOS CHECK (PRECIO_ANTERIOR >= 0 AND PRECIO_OFERTA >= 0),
    CONSTRAINT CHK_OFERTA_DESCUENTO CHECK (PRECIO_OFERTA <= PRECIO_ANTERIOR),
    CONSTRAINT CHK_OFERTA_VIGENCIA CHECK (HASTA > DESDE)
);

-- ============================================================================
-- 4. CARRITO (validado en backend, persistencia opcional del MVP)
-- ============================================================================

CREATE TABLE CARRITO (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID    NUMBER(19),
    TOKEN_ANONIMO VARCHAR2(64),
    CONSTRAINT PK_CARRITO PRIMARY KEY (ID),
    CONSTRAINT UQ_CARRITO_USUARIO UNIQUE (USUARIO_ID),
    CONSTRAINT UQ_CARRITO_TOKEN UNIQUE (TOKEN_ANONIMO),
    CONSTRAINT FK_CARRITO_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIO (ID) ON DELETE CASCADE,
    CONSTRAINT CHK_CARRITO_DUENIO
        CHECK (USUARIO_ID IS NOT NULL OR TOKEN_ANONIMO IS NOT NULL)
);

CREATE TABLE CARRITO_ITEM (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CARRITO_ID  NUMBER(19) NOT NULL,
    PRODUCTO_ID NUMBER(19) NOT NULL,
    CANTIDAD    NUMBER(2)  DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CARRITO_ITEM PRIMARY KEY (ID),
    CONSTRAINT UQ_CARRITO_ITEM UNIQUE (CARRITO_ID, PRODUCTO_ID),
    CONSTRAINT FK_CARRITO_ITEM_CARRITO FOREIGN KEY (CARRITO_ID)
        REFERENCES CARRITO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_CARRITO_ITEM_PRODUCTO FOREIGN KEY (PRODUCTO_ID)
        REFERENCES PRODUCTO (ID),
    CONSTRAINT CHK_CARRITO_ITEM_CANTIDAD CHECK (CANTIDAD BETWEEN 1 AND 10)
);

-- ============================================================================
-- 5. PEDIDOS
-- ============================================================================

CREATE TABLE PEDIDO (
    ID                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NUMERO             VARCHAR2(20)  NOT NULL,
    USUARIO_ID         NUMBER(19),
    TIPO_ENTREGA       VARCHAR2(20)  NOT NULL,
    CONTACTO_NOMBRE    VARCHAR2(100) NOT NULL,
    CONTACTO_CORREO    VARCHAR2(100) NOT NULL,
    CONTACTO_TELEFONO  VARCHAR2(20)  NOT NULL,
    DIRECCION          VARCHAR2(300),
    REGION_CODIGO      VARCHAR2(10),
    COMUNA_CODIGO      VARCHAR2(10),
    METODO_PAGO        VARCHAR2(20)  NOT NULL,
    ESTADO             VARCHAR2(25)  NOT NULL,
    SUBTOTAL           NUMBER(10)    DEFAULT 0 NOT NULL,
    AHORRO             NUMBER(10)    DEFAULT 0 NOT NULL,
    COSTO_DESPACHO     NUMBER(10)    DEFAULT 0 NOT NULL,
    TOTAL              NUMBER(10)    NOT NULL,
    TRANSPORTISTA      VARCHAR2(100),
    CODIGO_SEGUIMIENTO VARCHAR2(60),
    IDEMPOTENCY_KEY    VARCHAR2(64),
    EXPIRA_EN          TIMESTAMP,
    CONSTRAINT PK_PEDIDO PRIMARY KEY (ID),
    CONSTRAINT UQ_PEDIDO_NUMERO UNIQUE (NUMERO),
    CONSTRAINT UQ_PEDIDO_IDEMPOTENCIA UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT FK_PEDIDO_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIO (ID),
    CONSTRAINT FK_PEDIDO_REGION FOREIGN KEY (REGION_CODIGO)
        REFERENCES REGION (CODIGO),
    CONSTRAINT FK_PEDIDO_COMUNA FOREIGN KEY (COMUNA_CODIGO)
        REFERENCES COMUNA (CODIGO),
    CONSTRAINT CHK_PEDIDO_ENTREGA CHECK (TIPO_ENTREGA IN ('DESPACHO','RETIRO')),
    CONSTRAINT CHK_PEDIDO_PAGO CHECK (METODO_PAGO IN ('TARJETA','TRANSFERENCIA')),
    CONSTRAINT CHK_PEDIDO_ESTADO CHECK (ESTADO IN (
        'PENDIENTE_PAGO','PAGO_RECHAZADO','PAGADO','EN_PREPARACION',
        'ENVIADO','LISTO_PARA_RETIRO','ENTREGADO','EXPIRADO',
        'CANCELADO','DEVUELTO')),
    CONSTRAINT CHK_PEDIDO_MONTOS CHECK (
        SUBTOTAL >= 0 AND AHORRO >= 0 AND COSTO_DESPACHO >= 0 AND TOTAL >= 0),
    CONSTRAINT CHK_PEDIDO_DESPACHO CHECK (
        TIPO_ENTREGA = 'RETIRO'
        OR (DIRECCION IS NOT NULL AND REGION_CODIGO IS NOT NULL
            AND COMUNA_CODIGO IS NOT NULL))
);

CREATE TABLE PEDIDO_PRODUCTO (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PEDIDO_ID       NUMBER(19)   NOT NULL,
    PRODUCTO_ID     NUMBER(19)   NOT NULL,
    NOMBRE_SNAPSHOT VARCHAR2(100) NOT NULL,
    PRECIO_UNITARIO NUMBER(10)   NOT NULL,
    CANTIDAD        NUMBER(2)    NOT NULL,
    CONSTRAINT PK_PEDIDO_PRODUCTO PRIMARY KEY (ID),
    CONSTRAINT UQ_PEDIDO_PRODUCTO UNIQUE (PEDIDO_ID, PRODUCTO_ID),
    CONSTRAINT FK_PEDIDO_PRODUCTO_PED FOREIGN KEY (PEDIDO_ID)
        REFERENCES PEDIDO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PEDIDO_PRODUCTO_PRD FOREIGN KEY (PRODUCTO_ID)
        REFERENCES PRODUCTO (ID),
    CONSTRAINT CHK_PEDIDO_PRODUCTO_CANT CHECK (CANTIDAD BETWEEN 1 AND 10),
    CONSTRAINT CHK_PEDIDO_PRODUCTO_PRECIO CHECK (PRECIO_UNITARIO >= 0)
);

CREATE TABLE HISTORIAL_ESTADO_PEDIDO (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PEDIDO_ID        NUMBER(19) NOT NULL,
    ESTADO_ANTERIOR  VARCHAR2(25),
    ESTADO_NUEVO     VARCHAR2(25) NOT NULL,
    ACTOR_USUARIO_ID NUMBER(19),
    MOTIVO           VARCHAR2(300),
    FECHA            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HISTORIAL_ESTADO_PEDIDO PRIMARY KEY (ID),
    CONSTRAINT FK_HISTORIAL_PEDIDO FOREIGN KEY (PEDIDO_ID)
        REFERENCES PEDIDO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_HISTORIAL_USUARIO FOREIGN KEY (ACTOR_USUARIO_ID)
        REFERENCES USUARIO (ID)
);

CREATE TABLE MOVIMIENTO_STOCK (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PRODUCTO_ID NUMBER(19) NOT NULL,
    TIPO        VARCHAR2(20) NOT NULL,
    CANTIDAD    NUMBER(10) NOT NULL,
    MOTIVO      VARCHAR2(200),
    PEDIDO_ID   NUMBER(19),
    USUARIO_ID  NUMBER(19),
    CONSTRAINT PK_MOVIMIENTO_STOCK PRIMARY KEY (ID),
    CONSTRAINT FK_MOVIMIENTO_PRODUCTO FOREIGN KEY (PRODUCTO_ID)
        REFERENCES PRODUCTO (ID),
    CONSTRAINT FK_MOVIMIENTO_PEDIDO FOREIGN KEY (PEDIDO_ID)
        REFERENCES PEDIDO (ID),
    CONSTRAINT FK_MOVIMIENTO_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIO (ID),
    CONSTRAINT CHK_MOVIMIENTO_TIPO CHECK (TIPO IN (
        'ENTRADA','SALIDA','RESERVA','LIBERACION','AJUSTE')),
    CONSTRAINT CHK_MOVIMIENTO_CANTIDAD CHECK (CANTIDAD > 0)
);

-- ============================================================================
-- 6. PAGOS
-- ============================================================================

CREATE TABLE TRANSACCION_PAGO (
    ID                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PEDIDO_ID          NUMBER(19)   NOT NULL,
    PROVEEDOR          VARCHAR2(50) NOT NULL,
    REFERENCIA_EXTERNA VARCHAR2(100) NOT NULL,
    MONTO              NUMBER(10)   NOT NULL,
    ESTADO             VARCHAR2(20) NOT NULL,
    CODIGO_RESPUESTA   VARCHAR2(50),
    MOTIVO             VARCHAR2(300),
    IDEMPOTENCY_KEY    VARCHAR2(64),
    CONSTRAINT PK_TRANSACCION_PAGO PRIMARY KEY (ID),
    CONSTRAINT UQ_TRANSACCION_REF UNIQUE (REFERENCIA_EXTERNA),
    CONSTRAINT UQ_TRANSACCION_IDEMP UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT FK_TRANSACCION_PEDIDO FOREIGN KEY (PEDIDO_ID)
        REFERENCES PEDIDO (ID),
    CONSTRAINT CHK_TRANSACCION_ESTADO CHECK (ESTADO IN (
        'INICIADA','APROBADA','RECHAZADA','PENDIENTE','ANULADA')),
    CONSTRAINT CHK_TRANSACCION_MONTO CHECK (MONTO >= 0)
);

-- ============================================================================
-- 7. VENTA Y BOLETA (estructura, sin integracion SII en el MVP)
-- ============================================================================

CREATE TABLE VENTA (
    ID         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PEDIDO_ID  NUMBER(19) NOT NULL,
    FECHA      TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
    MONTO_NETO NUMBER(10) NOT NULL,
    MONTO_IVA  NUMBER(10) NOT NULL,
    TOTAL      NUMBER(10) NOT NULL,
    ESTADO     VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_VENTA PRIMARY KEY (ID),
    CONSTRAINT UQ_VENTA_PEDIDO UNIQUE (PEDIDO_ID),
    CONSTRAINT FK_VENTA_PEDIDO FOREIGN KEY (PEDIDO_ID)
        REFERENCES PEDIDO (ID),
    CONSTRAINT CHK_VENTA_ESTADO CHECK (ESTADO IN ('PENDIENTE','EMITIDA','ANULADA')),
    CONSTRAINT CHK_VENTA_MONTOS CHECK (
        MONTO_NETO >= 0 AND MONTO_IVA >= 0 AND TOTAL >= 0
        AND TOTAL = MONTO_NETO + MONTO_IVA)
);

CREATE TABLE BOLETA (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    VENTA_ID       NUMBER(19)   NOT NULL,
    FOLIO          VARCHAR2(30) NOT NULL,
    TIPO_DOCUMENTO VARCHAR2(10) NOT NULL,
    RUT_RECEPTOR   VARCHAR2(12),
    FECHA_EMISION  TIMESTAMP    NOT NULL,
    MONTO_NETO     NUMBER(10)   NOT NULL,
    MONTO_IVA      NUMBER(10)   NOT NULL,
    TOTAL          NUMBER(10)   NOT NULL,
    ESTADO         VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_BOLETA PRIMARY KEY (ID),
    CONSTRAINT UQ_BOLETA_VENTA UNIQUE (VENTA_ID),
    CONSTRAINT UQ_BOLETA_FOLIO UNIQUE (FOLIO),
    CONSTRAINT FK_BOLETA_VENTA FOREIGN KEY (VENTA_ID)
        REFERENCES VENTA (ID),
    CONSTRAINT CHK_BOLETA_TIPO CHECK (TIPO_DOCUMENTO IN ('BOLETA','FACTURA')),
    CONSTRAINT CHK_BOLETA_ESTADO CHECK (ESTADO IN ('EMITIDA','ANULADA')),
    CONSTRAINT CHK_BOLETA_MONTOS CHECK (
        MONTO_NETO >= 0 AND MONTO_IVA >= 0 AND TOTAL >= 0
        AND TOTAL = MONTO_NETO + MONTO_IVA)
);

CREATE TABLE DETALLE_BOLETA (
    ID                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    BOLETA_ID          NUMBER(19)   NOT NULL,
    PEDIDO_PRODUCTO_ID NUMBER(19)   NOT NULL,
    DESCRIPCION        VARCHAR2(200) NOT NULL,
    CANTIDAD           NUMBER(2)    NOT NULL,
    PRECIO_UNITARIO    NUMBER(10)   NOT NULL,
    CONSTRAINT PK_DETALLE_BOLETA PRIMARY KEY (ID),
    CONSTRAINT UQ_DETALLE_BOLETA UNIQUE (BOLETA_ID, PEDIDO_PRODUCTO_ID),
    CONSTRAINT FK_DETALLE_BOLETA FOREIGN KEY (BOLETA_ID)
        REFERENCES BOLETA (ID) ON DELETE CASCADE,
    CONSTRAINT FK_DETALLE_PEDPROD FOREIGN KEY (PEDIDO_PRODUCTO_ID)
        REFERENCES PEDIDO_PRODUCTO (ID),
    CONSTRAINT CHK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CHK_DETALLE_PRECIO CHECK (PRECIO_UNITARIO >= 0)
);

-- ============================================================================
-- 8. CONTENIDO Y CONTACTO
-- ============================================================================

CREATE TABLE ENTRADAS_BLOG (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    AUTOR_USUARIO_ID NUMBER(19)    NOT NULL,
    SLUG             VARCHAR2(100) NOT NULL,
    TITULO           VARCHAR2(200) NOT NULL,
    RESUMEN          VARCHAR2(500),
    IMAGEN_URL       VARCHAR2(500),
    BLOQUES          CLOB,
    PUBLICADA        CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_ENTRADAS_BLOG PRIMARY KEY (ID),
    CONSTRAINT UQ_ENTRADAS_BLOG_SLUG UNIQUE (SLUG),
    CONSTRAINT FK_BLOG_USUARIO FOREIGN KEY (AUTOR_USUARIO_ID)
        REFERENCES USUARIO (ID),
    CONSTRAINT CHK_BLOG_PUBLICADA CHECK (PUBLICADA IN ('S','N')),
    CONSTRAINT CHK_BLOG_BLOQUES CHECK (BLOQUES IS JSON)
);

CREATE TABLE MENSAJE_CONTACTO (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    RESPONDIDO_POR NUMBER(19),
    NOMBRE         VARCHAR2(100) NOT NULL,
    CORREO         VARCHAR2(100) NOT NULL,
    COMENTARIO     VARCHAR2(500) NOT NULL,
    ESTADO         VARCHAR2(15) DEFAULT 'NUEVO' NOT NULL,
    CONSTRAINT PK_MENSAJE_CONTACTO PRIMARY KEY (ID),
    CONSTRAINT FK_CONTACTO_USUARIO FOREIGN KEY (RESPONDIDO_POR)
        REFERENCES USUARIO (ID),
    CONSTRAINT CHK_CONTACTO_ESTADO CHECK (ESTADO IN ('NUEVO','LEIDO','RESPONDIDO')),
    CONSTRAINT CHK_CONTACTO_COMENTARIO CHECK (LENGTH(COMENTARIO) <= 500)
);

